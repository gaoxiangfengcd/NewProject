function fixRelated(pages: SeoLandingPage[]): SeoLandingPage[] {
  const slugs = new Set(pages.map((p) => p.slug))
  return pages.map((page) => ({
    ...page,
    related: page.related.filter((slug) => slugs.has(slug) && slug !== page.slug),
  }))
}

export const SEO_PAGES: SeoLandingPage[] = fixRelated(SEO_LANDING_PAGES)

export const SEO_PAGE_MAP: Record<string, SeoLandingPage> = Object.fromEntries(
  SEO_PAGES.map((page) => [page.slug, page]),
)

export function getSeoPage(slug: string): SeoLandingPage | undefined {
  return SEO_PAGE_MAP[slug]
}

export function allSeoSlugs(): string[] {
  return SEO_PAGES.map((page) => page.slug)
}
